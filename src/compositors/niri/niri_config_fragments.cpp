namespace niri_fragments {

  namespace {

    // Baselines from the plugin (panel.luau BASE). Springs are niri stiffness at damping 1.0 —
    // critically damped, so nothing overshoots — and durations are milliseconds.
    constexpr double kWorkspace = 380.0;
    constexpr double kMovement = 420.0; // view / window movement / resize: one physical system
    constexpr double kOverview = 400.0;
    constexpr double kOpen = 360.0;
    constexpr double kClose = 240.0;
    constexpr double kScreenshot = 260.0;
    constexpr double kRecent = 600.0;
    constexpr double kExitConfirm = 600.0;
    constexpr double kConfigNotification = 800.0;

    // Lua math.floor(x + 0.5): round half up, which differs from std::round for negatives only.
    int roundHalfUp(double x) { return static_cast<int>(std::floor(x + 0.5)); }

    // A spring gets stiffer with the square of the speed factor (period scales with 1/sqrt(k)).
    int spring(double base, double factor) { return std::max(1, roundHalfUp(base * factor * factor)); }
    int duration(double base, double factor) { return std::max(1, roundHalfUp(base / factor)); }

    std::string_view presetName(MotionPreset preset) {
      switch (preset) {
      case MotionPreset::Instant:
        return "Instant";
      case MotionPreset::Fast:
        return "Fast";
      case MotionPreset::Default:
        return "Default";
      case MotionPreset::Smooth:
        return "Smooth";
      case MotionPreset::Cinematic:
        return "Cinematic";
      }
      return "Smooth";
    }

    std::string sp(int stiffness) {
      return std::format("spring damping-ratio=1.0 stiffness={} epsilon=0.0001", stiffness);
    }

    // Open/close shaders, verbatim from the plugin: open leads with opacity so a window is readable
    // almost immediately; close fades while shrinking slightly.
    constexpr std::string_view kOpenShader = R"(        custom-shader r"
            vec4 open_color(vec3 coords_geo, vec3 size_geo) {
                float p = niri_clamped_progress;
                float scale = mix(0.92, 1.0, p);
                coords_geo = vec3((coords_geo.xy - vec2(0.5)) / scale + vec2(0.5), 1.0);
                vec3 coords_tex = niri_geo_to_tex * coords_geo;
                vec4 color = texture2D(niri_tex, coords_tex.st);
                // Opacity leads the scale so the window is readable almost immediately.
                return color * clamp(p * 1.5, 0.0, 1.0);
            }
        ")";
    constexpr std::string_view kCloseShader = R"(        custom-shader r"
            vec4 close_color(vec3 coords_geo, vec3 size_geo) {
                float p = niri_clamped_progress;
                float scale = mix(1.0, 0.95, p);
                coords_geo = vec3((coords_geo.xy - vec2(0.5)) / scale + vec2(0.5), 1.0);
                vec3 coords_tex = niri_geo_to_tex * coords_geo;
                vec4 color = texture2D(niri_tex, coords_tex.st);
                return color * (1.0 - p);
            }
        ")";

    double trim(std::int32_t percent) { return std::clamp(percent, 50, 200) / 100.0; }

  } // namespace

  std::string formatNumber(double value) {
    char buf[64];
    std::snprintf(buf, sizeof(buf), "%.4f", value);
    std::string s(buf);
    while (!s.empty() && s.back() == '0') {
      s.pop_back();
    }
    if (!s.empty() && s.back() == '.') {
      s.push_back('0');
    }
    return s;
  }

  float presetFactor(MotionPreset preset) noexcept {
    switch (preset) {
    case MotionPreset::Instant:
      return 3.0F;
    case MotionPreset::Fast:
      return 1.6F;
    case MotionPreset::Default:
      return 1.25F;
    case MotionPreset::Smooth:
      return 1.0F;
    case MotionPreset::Cinematic:
      return 0.8F;
    }
    return 1.0F;
  }

  float effectiveShellSpeed(const ShellConfig::AnimationConfig& animation) noexcept {
    return std::clamp(kShellBaseSpeed * presetFactor(animation.preset) * animation.speed, 0.05F, 4.0F);
  }

  std::string renderAnimations(const ShellConfig::AnimationConfig& a) {
    const double f = presetFactor(a.preset);
    // Speed is schema-clamped to >= 0.1, so slowdown is bounded at 10.
    const double speed = std::max(0.1, static_cast<double>(a.speed));

    std::string out = std::format(
        "// Generated by Zynith Shell from [shell.animation]. Change it in Zynith Corner -> Motion;\n"
        "// edits made here are overwritten on the next change.\n"
        "// Preset: {}  speed x{}  trims open {}% close {}% movement {}% overview {}%\n\n",
        presetName(a.preset), formatNumber(speed), std::clamp(a.niriOpen, 50, 200), std::clamp(a.niriClose, 50, 200),
        std::clamp(a.niriMovement, 50, 200), std::clamp(a.niriOverview, 50, 200)
    );
    if (!a.enabled) {
      out += "animations {\n    off\n}\n";
      return out;
    }

    const double movement = f * trim(a.niriMovement);
    out += "animations {\n";
    out += std::format("    slowdown {}\n\n", formatNumber(1.0 / speed));
    out += std::format("    workspace-switch {{\n        {}\n    }}\n\n", sp(spring(kWorkspace, movement)));
    out += "    // One physical system: niri drives these together, so they share parameters.\n";
    out += std::format("    horizontal-view-movement {{\n        {}\n    }}\n", sp(spring(kMovement, movement)));
    out += std::format("    window-movement {{\n        {}\n    }}\n", sp(spring(kMovement, movement)));
    out += std::format("    window-resize {{\n        {}\n    }}\n\n", sp(spring(kMovement, movement)));
    out += std::format(
        "    overview-open-close {{\n        {}\n    }}\n\n", sp(spring(kOverview, f * trim(a.niriOverview)))
    );
    out += std::format(
        "    window-open {{\n        duration-ms {}\n        curve \"cubic-bezier\" 0.05 0.9 0.1 1.0\n{}\n    }}\n\n",
        duration(kOpen, f * trim(a.niriOpen)), kOpenShader
    );
    out += std::format(
        "    window-close {{\n        duration-ms {}\n        curve \"cubic-bezier\" 0.2 0.0 0.0 1.0\n{}\n    }}\n\n",
        duration(kClose, f * trim(a.niriClose)), kCloseShader
    );
    out += std::format(
        "    screenshot-ui-open {{\n        duration-ms {}\n        curve \"cubic-bezier\" 0.05 0.9 0.1 1.0\n    }}\n",
        duration(kScreenshot, f)
    );
    out += std::format(
        "    recent-windows-close {{\n        spring damping-ratio=1.0 stiffness={} epsilon=0.001\n    }}\n",
        spring(kRecent, f)
    );
    out += std::format(
        "    exit-confirmation-open-close {{\n        spring damping-ratio=1.0 stiffness={} epsilon=0.001\n    }}\n",
        spring(kExitConfirm, f)
    );
    out += std::format(
        "    config-notification-open-close {{\n        spring damping-ratio=1.0 stiffness={} epsilon=0.001\n    }}\n",
        spring(kConfigNotification, f)
    );
    out += "}\n";
    return out;
  }

  BlurParams blurParams(int strength) noexcept {
    const double s = std::clamp(strength, 0, 100) / 100.0;
    // Linear in both: passes 1..5 and offset 1.0..7.0, which puts 50 exactly on the tuned
    // passes 3 / offset 4.0 this desktop has used since Phase 1.
    return BlurParams{
        .passes = 1 + roundHalfUp(4.0 * s),
        .offset = static_cast<float>(1.0 + 6.0 * s),
    };
  }

  std::string renderGlass(const ShellConfig::GlassConfig& glass) {
    const auto p = blurParams(glass.blurStrength);
    return std::format(
        "// Generated by Zynith Shell from [shell.glass]. Change it in Zynith Corner -> Glass;\n"
        "// edits made here are overwritten on the next change.\n"
        "// Xray blur: the wallpaper is blurred once and reused, so strength costs little per frame.\n"
        "// blur_strength {} -> passes {} offset {}\n\n"
        "blur {{\n    passes {}\n    offset {}\n    noise 0.025\n    saturation 1.25\n}}\n",
        std::clamp(glass.blurStrength, 0, 100), p.passes, formatNumber(p.offset), p.passes, formatNumber(p.offset)
    );
  }

} // namespace niri_fragments
