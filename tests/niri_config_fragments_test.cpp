// niri configuration fragments (ADR-0015): the shell-side port of the retired Motion plugin's
// renderer, and the glass blur renderer. Pure functions, so these are exact-output tests.

#include "compositors/niri/niri_config_fragments.h"

#include <iostream>
#include <string>
#include <string_view>

namespace {

  int failures = 0;

  void check(bool cond, const char* msg) {
    if (!cond) {
      std::cerr << "FAIL: " << msg << '\n';
      ++failures;
    }
  }

  std::string body(const std::string& text) {
    const auto at = text.find("animations {");
    return at == std::string::npos ? std::string{} : text.substr(at);
  }

  // The Motion plugin's last output on this machine (preset Cinematic, speed 1.0, every trim
  // 100 %), captured before the plugin was retired. The port must reproduce it byte for byte;
  // only the comment header above `animations {` is allowed to differ.
  constexpr std::string_view kPluginCinematicBody = R"KDL(animations {
    slowdown 1.0

    workspace-switch {
        spring damping-ratio=1.0 stiffness=243 epsilon=0.0001
    }

    // One physical system: niri drives these together, so they share parameters.
    horizontal-view-movement {
        spring damping-ratio=1.0 stiffness=269 epsilon=0.0001
    }
    window-movement {
        spring damping-ratio=1.0 stiffness=269 epsilon=0.0001
    }
    window-resize {
        spring damping-ratio=1.0 stiffness=269 epsilon=0.0001
    }

    overview-open-close {
        spring damping-ratio=1.0 stiffness=256 epsilon=0.0001
    }

    window-open {
        duration-ms 450
        curve "cubic-bezier" 0.05 0.9 0.1 1.0
        custom-shader r"
            vec4 open_color(vec3 coords_geo, vec3 size_geo) {
                float p = niri_clamped_progress;
                float scale = mix(0.92, 1.0, p);
                coords_geo = vec3((coords_geo.xy - vec2(0.5)) / scale + vec2(0.5), 1.0);
                vec3 coords_tex = niri_geo_to_tex * coords_geo;
                vec4 color = texture2D(niri_tex, coords_tex.st);
                // Opacity leads the scale so the window is readable almost immediately.
                return color * clamp(p * 1.5, 0.0, 1.0);
            }
        "
    }

    window-close {
        duration-ms 300
        curve "cubic-bezier" 0.2 0.0 0.0 1.0
        custom-shader r"
            vec4 close_color(vec3 coords_geo, vec3 size_geo) {
                float p = niri_clamped_progress;
                float scale = mix(1.0, 0.95, p);
                coords_geo = vec3((coords_geo.xy - vec2(0.5)) / scale + vec2(0.5), 1.0);
                vec3 coords_tex = niri_geo_to_tex * coords_geo;
                vec4 color = texture2D(niri_tex, coords_tex.st);
                return color * (1.0 - p);
            }
        "
    }

    screenshot-ui-open {
        duration-ms 325
        curve "cubic-bezier" 0.05 0.9 0.1 1.0
    }
    recent-windows-close {
        spring damping-ratio=1.0 stiffness=384 epsilon=0.001
    }
    exit-confirmation-open-close {
        spring damping-ratio=1.0 stiffness=384 epsilon=0.001
    }
    config-notification-open-close {
        spring damping-ratio=1.0 stiffness=512 epsilon=0.001
    }
}
)KDL";

} // namespace

int main() {
  using namespace niri_fragments;

  // --- faithful port ------------------------------------------------------------------------
  {
    ShellConfig::AnimationConfig a;
    a.preset = MotionPreset::Cinematic;
    a.speed = 1.0F;
    const auto out = renderAnimations(a);
    check(body(out) == kPluginCinematicBody, "cinematic body matches the plugin's output exactly");
    check(out.find("Generated by Zynith Shell") != std::string::npos, "header names the shell as generator");
    if (body(out) != kPluginCinematicBody) {
      std::cerr << "--- got ---\n" << body(out) << "--- want ---\n" << kPluginCinematicBody;
    }
  }

  // --- shell speed: one speed and one preset shape both halves -------------------------------
  {
    ShellConfig::AnimationConfig a;
    a.preset = MotionPreset::Cinematic;
    a.speed = 1.0F;
    const float s = effectiveShellSpeed(a);
    check(s > 0.6399F && s < 0.6401F, "cinematic @1.0 gives the 0.64 the plugin wrote to motion.toml");
    a.preset = MotionPreset::Smooth;
    const float smooth = effectiveShellSpeed(a);
    check(smooth > 0.7999F && smooth < 0.8001F, "smooth @1.0 gives the 0.8 shell baseline");
    a.speed = 100.0F;
    check(effectiveShellSpeed(a) <= 4.0F, "shell speed is clamped to MotionService's range");
  }

  // --- disabled -----------------------------------------------------------------------------
  {
    ShellConfig::AnimationConfig a;
    a.enabled = false;
    const auto out = renderAnimations(a);
    check(body(out) == "animations {\n    off\n}\n", "disabled renders animations off and nothing else");
  }

  // --- trims: floor of 50 so a 0 % trim cannot divide by zero ---------------------------------
  {
    ShellConfig::AnimationConfig a;
    a.niriOpen = 0;
    a.niriClose = -40;
    const auto out = renderAnimations(a);
    check(out.find("inf") == std::string::npos && out.find("nan") == std::string::npos, "no inf/nan with a 0 trim");
    ShellConfig::AnimationConfig fifty;
    fifty.niriOpen = 50;
    fifty.niriClose = 50;
    check(body(out) == body(renderAnimations(fifty)), "trims below 50 behave exactly like 50");
  }

  // --- determinism: identical input, identical output (the writer relies on this to skip) ----
  {
    ShellConfig::AnimationConfig a;
    a.preset = MotionPreset::Fast;
    a.niriMovement = 135;
    check(renderAnimations(a) == renderAnimations(a), "rendering is deterministic");
  }

  // --- speed feeds niri slowdown ---------------------------------------------------------------
  {
    ShellConfig::AnimationConfig a;
    a.speed = 0.64F;
    check(renderAnimations(a).find("    slowdown 1.5625\n") != std::string::npos, "slowdown = 1 / speed");
  }

  // --- glass blur ------------------------------------------------------------------------------
  {
    check(blurParams(50).passes == 3 && blurParams(50).offset == 4.0F, "strength 50 = passes 3 / offset 4.0");
    check(blurParams(0).passes == 1 && blurParams(0).offset == 1.0F, "strength 0 = passes 1 / offset 1.0");
    check(blurParams(100).passes == 5 && blurParams(100).offset == 7.0F, "strength 100 = passes 5 / offset 7.0");
    check(blurParams(250).passes == 5 && blurParams(-9).passes == 1, "strength is clamped to 0-100");
    ShellConfig::GlassConfig g;
    const auto out = renderGlass(g);
    const std::string_view block = "blur {\n    passes 3\n    offset 4.0\n    noise 0.025\n    saturation 1.25\n}\n";
    check(out.size() >= block.size() && out.substr(out.size() - block.size()) == block,
          "default glass reproduces the blur block config.kdl carried before it moved");
  }

  // --- number formatting identical to the plugin's fmt() ---------------------------------------
  {
    check(formatNumber(1.0) == "1.0", "1.0");
    check(formatNumber(0.8) == "0.8", "0.8");
    check(formatNumber(1.5625) == "1.5625", "1.5625");
    check(formatNumber(10.0) == "10.0", "10.0");
  }

  if (failures == 0) {
    std::cout << "niri config fragments test passed\n";
    return 0;
  }
  std::cerr << failures << " check(s) failed\n";
  return 1;
}
