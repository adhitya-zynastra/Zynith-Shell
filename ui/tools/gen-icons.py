def main():
    table = json.load(open(SOURCE))
    lines = [".pragma library", "", "// Generated by tools/gen-icons.py from assets/fonts/tabler.json. Do not edit.", ""]
    lines.append("var glyphs = {")
    missing = []
    for name in sorted(set(ICONS)):
        entry = table.get(name)
        if entry is None:
            missing.append(name)
            continue
        code = int(entry["codepoint"][2:], 16)
        if code > 0xFFFF:  # JS strings are UTF-16
            code -= 0x10000
            text = f"\\u{0xD800 + (code >> 10):04x}\\u{0xDC00 + (code & 0x3FF):04x}"
        else:
            text = f"\\u{code:04x}"
        lines.append(f'    "{name}": "{text}",')
    lines.append("};")
    lines.append("")
    open(OUT, "w").write("\n".join(lines))
    print(f"{len(ICONS) - len(missing)} icons -> {os.path.relpath(OUT, UI)}")
    if missing:
        print("missing:", " ".join(missing))


if __name__ == "__main__":
    main()
