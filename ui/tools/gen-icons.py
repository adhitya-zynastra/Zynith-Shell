#!/usr/bin/env python3
"""Writes Common/IconMap.js: name -> glyph for the icons the UI uses.

The full Tabler map is 470 KB of JSON; parsing it in the shell at startup would cost more than every icon
we draw. Add a name to ICONS and rerun.
"""
import json
import os

HERE = os.path.dirname(os.path.abspath(__file__))
UI = os.path.dirname(HERE)
SOURCE = os.path.join(UI, "..", "assets", "fonts", "tabler.json")
OUT = os.path.join(UI, "Common", "IconMap.js")

ICONS = """
adjustments-horizontal battery battery-1 battery-2 battery-3 battery-4 battery-charging bluetooth bluetooth-connected
bluetooth-off bolt brightness-up calendar chevron-down chevron-left chevron-right circle clock cpu device-desktop
device-laptop gauge layout-grid leaf lock moon music player-pause-filled player-play-filled player-skip-back-filled
player-skip-forward-filled plus point-filled power rocket settings sparkles sun volume volume-2 volume-3 volume-off
wifi wifi-1 wifi-2 wifi-off x layers-intersect stack-2 activity disc search apps clipboard clipboard-list photo trash
corner-down-left bell bell-off bell-ringing microphone microphone-off coffee sunset-2 brightness-down
keyboard logout refresh zzz power-off grip-vertical dots-vertical calculator window app-window mood-smile math-function
""".split()


def main():
    table = json.load(open(SOURCE))
    lines = [".pragma library", "", "// Generated by tools/gen-icons.py from assets/fonts/tabler.json. Do not edit.", ""]
    lines.append("var glyphs = {")
    missing = []
    for name in sorted(set(ICONS)):
        entry = table.get(name)
        if entry is None:
            missing.append(name)
            continue
        code = int(entry["codepoint"][2:], 16)
        if code > 0xFFFF:  # JS strings are UTF-16
            code -= 0x10000
            text = f"\\u{0xD800 + (code >> 10):04x}\\u{0xDC00 + (code & 0x3FF):04x}"
        else:
            text = f"\\u{code:04x}"
        lines.append(f'    "{name}": "{text}",')
    lines.append("};")
    lines.append("")
    open(OUT, "w").write("\n".join(lines))
    print(f"{len(ICONS) - len(missing)} icons -> {os.path.relpath(OUT, UI)}")
    if missing:
        print("missing:", " ".join(missing))


if __name__ == "__main__":
    main()
